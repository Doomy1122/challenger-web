import fs from "node:fs";
import path from "node:path";

const categories = ["df-26", "df-25", "df-24", "df-23", "df-22"];
const root = process.cwd();
const galleryRoot = path.join(root, "public", "gallery");
const outputDir = path.join(root, "app", "generated");
const outputFile = path.join(outputDir, "galleryManifest.ts");
const imagePattern = /\.(jpg|jpeg|png|webp|gif|heic)$/i;

const manifest = {};

for (const category of categories) {
  const dir = path.join(galleryRoot, category);
  let files = [];

  try {
    files = fs
      .readdirSync(dir, { withFileTypes: true })
      .filter((entry) => entry.isFile() && imagePattern.test(entry.name))
      .map((entry) => `/gallery/${category}/${entry.name}`)
      .sort((a, b) => a.localeCompare(b));
  } catch {
    files = [];
  }

  manifest[category] = files;
}

fs.mkdirSync(outputDir, { recursive: true });
fs.writeFileSync(
  outputFile,
  `// AUTO-GENERATED by scripts/generate-gallery-manifest.mjs\n// Do not edit manually. Add/remove files under public/gallery/df-* and rerun dev/build.\n\nexport const galleryManifest = ${JSON.stringify(manifest, null, 2)} as const;\n`,
  "utf8",
);

console.log(`Generated gallery manifest: ${Object.values(manifest).reduce((sum, list) => sum + list.length, 0)} images`);
